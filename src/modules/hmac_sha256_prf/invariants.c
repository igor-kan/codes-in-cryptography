#include "interface.h"
hmac_sha256_prf_err_t hmac_sha256_prf_verify_invariants(void) {
    // RFC 4231 Case 2: Key="Jefe", Data="what do ya want for nothing?"
    const uint8_t expected[32] = {
        0x5b,0xdc,0xc1,0x46,0xbf,0x60,0x75,0x4e,0x6a,0x04,0x24,0x26,0x08,0x95,0x75,0xc7,
        0x5a,0x00,0x3f,0x08,0x9d,0x27,0x39,0x83,0x9d,0xec,0x58,0xb9,0x64,0xec,0x38,0x43
    };
    uint8_t out[32];
    hmac_sha256_prf_mac((const uint8_t*)"Jefe", 4, (const uint8_t*)"what do ya want for nothing?", 28, out);
    return hmac_sha256_prf_ct_eq32(out, expected) ? HMAC_SHA256_PRF_OK : HMAC_SHA256_PRF_ERR_INVARIANT;
}
