#include "interface.h"
#include <string.h>

hchacha20_xchacha_kdf_err_t hchacha20_verify_rfc_vector(void) {
    const uint8_t key[32] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    const uint8_t nonce[16] = {
        0x00,0x00,0x00,0x09,0x00,0x00,0x00,0x4a,0x00,0x00,0x00,0x00,0x31,0x41,0x59,0x27
    };
    const uint8_t expected[32] = {
        0x82,0x41,0x3b,0x42,0x27,0xb2,0x7b,0xfe,0xd3,0x0e,0x42,0x50,0x8a,0x87,0x7d,0x73,
        0xa0,0xf9,0xe4,0xd5,0x8a,0x74,0xa8,0x53,0xc1,0x2e,0xc4,0x13,0x26,0xd3,0xec,0xdc
    };
    uint8_t got[32];
    hchacha20_derive(key, nonce, got);
    return memcmp(got, expected, 32) == 0 ? HCHACHA20_XCHACHA_KDF_OK : HCHACHA20_XCHACHA_KDF_ERR_INVARIANT;
}
