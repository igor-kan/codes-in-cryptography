#include "interface.h"
#include <string.h>

aes128_fips197_cipher_err_t aes128_verify_fips197_b(void) {
    const uint8_t key[16] = {0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c};
    const uint8_t pt[16]  = {0x32,0x43,0xf6,0xa8,0x88,0x5a,0x30,0x8d,0x31,0x31,0x98,0xa2,0xe0,0x37,0x07,0x34};
    const uint8_t exp[16] = {0x39,0x25,0x84,0x1d,0x02,0xdc,0x09,0xfb,0xdc,0x11,0x85,0x97,0x19,0x6a,0x0b,0x32};
    aes128_ctx_t ctx;
    aes128_init(&ctx, key);
    uint8_t ct[16], dec[16];
    aes128_encrypt_block(&ctx, pt, ct);
    if (memcmp(ct, exp, 16) != 0) return AES128_FIPS197_CIPHER_ERR_INVARIANT;
    aes128_decrypt_block(&ctx, ct, dec);
    if (memcmp(dec, pt, 16) != 0) return AES128_FIPS197_CIPHER_ERR_INVARIANT;
    return AES128_FIPS197_CIPHER_OK;
}
